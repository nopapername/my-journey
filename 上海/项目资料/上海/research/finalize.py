    digest=hashlib.sha256(body.encode()).hexdigest()
    if url in seen_url or digest in seen_body:
        prior=seen_url.get(url,seen_body.get(digest))
        rev.update(countable=False,note=f'排除：与原始ID {prior}重复URL或核心正文，不重复计数。')
