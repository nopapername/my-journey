def canonical(url):
    u=urlsplit(url)
    return urlunsplit((u.scheme,u.netloc.lower().removeprefix('www.'),u.path.rstrip('/'),u.query,''))

seen_url, seen_body = {}, {}
for r in rows:
    rev=reviews[r['id']]
    url=canonical(r['url'])
